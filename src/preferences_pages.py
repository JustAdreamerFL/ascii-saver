class PageBuilderMixin:


    def _layout_preferences(self):
        general = self._page_boxes["general"]
        appearance = self._page_boxes["appearance"]
        displays = self._page_boxes["displays"]
        animations = self._page_boxes["animations"]
        preview_page = self._page_boxes["preview"]
        rows = (
            ("general", "Automatic activation", self.enabled),
            ("general", "Idle watcher", self.watcher),
            ("general", "Respect application inhibitors", self.respect_inhibitors),
            ("general", "Protect fullscreen apps", self.ignore_fullscreen),
            ("general", "Idle delay (seconds)", self.delay),
            ("appearance", "Terminal font", self.font),
            ("appearance", "Background color", self.background),
            ("appearance", "Override effect RGB colors", self.override_effect_colors),
            ("appearance", "Cycle through palette colors", self.cycle_palette),
            ("appearance", "Reverse palette at the ends", self.palette_ping_pong),
            ("appearance", "Effects per color transition", self.palette_steps),
            ("appearance", "Shared palette", self.palette_box),
            ("appearance", "Different palettes on each display", self.per_monitor_visuals),
            ("animations", "Target output FPS", self.frame_rate),
            ("animations", "Keep final rendered frame (seconds)", self.effect_hold),
            ("animations", "Use ordered playlists", self.playlist_mode),
            ("displays", "Independent monitor settings", self.per_monitor),
        )
        subtitles = {
            "Automatic activation": "Start after the idle delay if no application is inhibiting it.",
            "Idle watcher": "Background service that detects when the desktop becomes idle.",
            "Respect application inhibitors": "Do not interrupt videos, games and presentations.",
            "Protect fullscreen apps": "Avoid launching over fullscreen windows (requires the KWin helper).",
            "Idle delay (seconds)": "",
            "Terminal font": "",
            "Background color": "",
            "Override effect RGB colors": "Turn off to preserve the original colors generated by each animation.",
            "Cycle through palette colors": "",
            "Effects per color transition": "1 = next color each effect; higher values blend gradually between effects.",
            "Target output FPS": "Frame-rate limit for shared monitors; not the compositor's presented FPS.",
            "Keep final rendered frame (seconds)": "Preserve the exact terminal frame and its ANSI colors.",
            "Use ordered playlists": "Use Playlist Editor to determine effect order.",
            "Independent monitor settings": "Configure individual FPS, artwork and effect synchronization.",
            "Different palettes on each display": "Override shared colors for selected displays.",
        }
        # Advanced palette parameters are discoverable without taking space
        # from every installation's basic color selection.
        self.palette_advanced = Adw.ExpanderRow(
            title="Color transitions", subtitle="Direction and blending between effects")
        self._adaptive_rows = []
        for section, label, widget in rows:
            advanced_palette = label in ("Reverse palette at the ends",
                                         "Effects per color transition")
            if isinstance(widget, Adw.SwitchRow):
                widget.set_title(label)
                widget.set_subtitle(subtitles.get(label, ""))
                if advanced_palette:
                    self.palette_advanced.add_row(widget)
                else:
                    self.section_groups[section].add(widget)
                row = widget
            else:
                if advanced_palette:
                    row = AdaptiveControlRow(label, subtitles.get(label, ""))
                    row.add_suffix(widget)
                    self.palette_advanced.add_row(row)
                else:
                    row = adaptive_action_row(self.section_groups[section], label, widget,
                                              subtitles.get(label))
                self._adaptive_rows.append(row)
            for identifier in ("delay", "frame_rate", "effect_hold", "palette_steps"):
                if widget is getattr(self, identifier):
                    install_numeric_reset(row, widget, default_for(identifier), Gtk)
                    break
            if label == "Target output FPS":
                self.global_fps_label = row
            if label == "Shared palette":
                self.shared_palette_label = row
                self.shared_palette_widget = widget
        self.section_groups["appearance"].add(self.palette_advanced)
        # The shared palette remains the fallback, including when overrides are on.
        background_reset = Gtk.Button.new_from_icon_name("edit-undo-symbolic")
        background_reset.add_css_class("flat")
        background_reset.set_tooltip_text("Restore default background color")
        def reset_background(*_args):
            rgba = Gdk.RGBA()
            rgba.parse("#000000")
            self.background.set_rgba(rgba)
        background_reset.connect("clicked", reset_background)
        for row in self._adaptive_rows:
            if row.get_title() == "Background color":
                row.add_suffix(background_reset)
                break

        self.fit_notice = Gtk.Label(xalign=0, wrap=True)
        self.fit_notice.add_css_class("dim-label")
        displays.append(self.fit_notice)
        self.fit_notice.set_visible(False)  # Details belong in diagnostics, not a permanent paragraph.
        palette_note = Gtk.Label(
            label="Palette colors change between effects, never mid-animation.",
            xalign=0, wrap=True)
        palette_note.add_css_class("dim-label")
        # Avoid repeating explanatory paragraphs below every settings group.
        palette_note.set_visible(False)
        appearance.append(palette_note)

        # These controls are powerful but are not independent of one another.
        # Keep the common controls legible, and describe the advanced options.
        advanced_group = make_group("Advanced")
        advanced = Adw.ExpanderRow(title="Animation timing",
                                   subtitle="Separate playback pacing from animation simulation; expand for details")
        for label, widget, subtitle in (
            ("Output pacing multiplier", self.speed, "Adjust how fast output frames are paced."),
            ("Frame dwell factor", self.duration_factor, "Longer delays; reduces actual FPS."),
            ("Elapsed-time simulation speed", self.time_scale, "Only affects clock-driven effects."),
            ("Frame-driven simulation hold", self.simulation_hold, "Repeat simulation frames at a fixed output cadence."),
        ):
            nested = AdaptiveControlRow(label, subtitle)
            self._adaptive_rows.append(nested)
            widget.set_valign(Gtk.Align.CENTER)
            if isinstance(widget, Gtk.Scale):
                widget.set_size_request(110, -1)
                widget.set_hexpand(True)
            nested.add_suffix(widget)
            control_id = next((key for key in ("speed", "duration_factor", "time_scale", "simulation_hold")
                               if widget is getattr(self, key)), None)
            if control_id:
                install_numeric_reset(nested, widget, default_for(control_id), Gtk)
            advanced.add_row(nested)
        advanced_group.add(advanced)
        animations.append(advanced_group)

        self.auto_fit_artwork.set_title("Auto-fit artwork")
        self.auto_fit_artwork.set_subtitle(
            "Independent: fit each display separately. Shared: use the smallest "
            "font needed to fit every display. Off: always use configured font."
        )
        self.section_groups["displays"].add(self.auto_fit_artwork)
        self.monitor_revealer = Gtk.Revealer()
        self.monitor_revealer.set_transition_type(Gtk.RevealerTransitionType.SLIDE_DOWN)
        monitor_sections = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=14)
        monitor_sections.append(self.monitor_rates_group)
        monitor_sections.append(self.monitor_colors_group)
        monitor_sections.append(self.monitor_artwork_group)
        monitor_options = make_group("Independent display behavior")
        self.shared_effect.set_title("Synchronize effect order")
        self.shared_effect.set_subtitle("Wait for every monitor to finish its effect and artwork hold before moving on.")
        monitor_options.add(self.shared_effect)
        self.monitor_options_group = monitor_options
        monitor_sections.append(monitor_options)
        self.monitor_revealer.set_child(monitor_sections)
        self.per_monitor.connect("notify::active", self._update_monitor_controls)
        self.per_monitor_visuals.connect("notify::active", self._update_monitor_controls)
        displays.append(self.monitor_revealer)

        tools = self._page_boxes["tools"]
        tools_group = make_group("Tools")
        for label, action, callback in (
            ("Effect Library", "Browse", self._open_gallery),
            ("Playlist Editor", "Open", self._open_playlist_editor),
            ("Edit Artwork", "Open", self._edit_default_artwork),
            ("Performance History", "Graphs", self._open_performance),
            ("Measured Durations", "Open", self._open_duration_profiles),
            ("Diagnostics", "Open", self._open_diagnostics),
        ):
            adaptive_append_action(tools_group, label, action, callback)
        tools.append(tools_group)

    def _make_raw_playlist(self):
        """Keep the legacy buffer as the single source of saved playlist JSON.

        The editor is a real window, not an expandable text field in the
        preferences scroller. Applying text marks the form dirty as usual.
        """
        group = make_group("Advanced playlist editing")
        _, button = adaptive_append_action(group, "Raw playlist JSON", "Open Editor",
                                  self._open_raw_playlist_editor,
                                  "For advanced users; normal playlist editing uses Playlist Editor.")
        self._page_boxes["animations"].append(group)
        self.playlists_text = Gtk.TextView(monospace=True)
        self.playlists_text.set_wrap_mode(Gtk.WrapMode.WORD_CHAR)

    def _open_raw_playlist_editor(self, _button=None):
        if getattr(self, "_playlist_json_window", None) is not None:
            self._playlist_json_window.present()
            return
        window = Adw.Window(title="Playlist JSON", transient_for=self)
        install_close_shortcuts(window, Gtk, Gdk)
        window.set_default_size(750, 640)
        toolbar = Adw.ToolbarView()
        header = Adw.HeaderBar()
        apply_button = Gtk.Button(label="Apply to Preferences")
        apply_button.add_css_class("suggested-action")
        header.pack_end(apply_button)
        toolbar.add_top_bar(header)
        editor = Gtk.TextView(monospace=True, top_margin=12, bottom_margin=12,
                              left_margin=16, right_margin=16)
        editor.set_wrap_mode(Gtk.WrapMode.WORD_CHAR)
        source = self.playlists_text.get_buffer()
        editor.get_buffer().set_text(source.get_text(source.get_start_iter(), source.get_end_iter(), False))
        def apply_edit(*_args):
            from playlist_engine import validate
            import json
            buf = editor.get_buffer()
            value = buf.get_text(buf.get_start_iter(), buf.get_end_iter(), False)
            try:
                validate(json.loads(value))
            except (ValueError, TypeError) as error:
                self._set_notice(f"Invalid playlist JSON: {error}", error=True)
                return
            source.set_text(value)
            self._mark_dirty()
            window.close()
        apply_button.connect("clicked", apply_edit)
        scroller = Gtk.ScrolledWindow(vexpand=True)
        scroller.set_child(editor)
        toolbar.set_content(scroller)
        window.set_content(toolbar)
        self._playlist_json_window = window
        window.connect("close-request", lambda *_: setattr(self, "_playlist_json_window", None) or False)
        window.present()
